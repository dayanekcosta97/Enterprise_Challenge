-- Smart HAS | Testes automaticos: package, trigger e Dynamic SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET SERVEROUTPUT ON

INSERT INTO SMH_ENTREGA (NUMERO, STATUS, RISCO)
VALUES ('ENT001', 'CRIADA', 'ALTO');

DECLARE
    V_ID NUMBER;
    V_TOTAL NUMBER;
    V_CURSOR SYS_REFCURSOR;
    V_NUMERO VARCHAR2(50);
    V_STATUS VARCHAR2(30);
    V_RISCO VARCHAR2(30);
BEGIN
    SELECT ID INTO V_ID FROM SMH_ENTREGA WHERE NUMERO = 'ENT001';

    PKG_SMART_HAS.PRC_ATUALIZAR_STATUS('ENT001', 'EM_TRANSITO');

    SELECT COUNT(*) INTO V_TOTAL FROM SMH_AUDITORIA
     WHERE ENTREGA_ID = V_ID AND STATUS_ANTERIOR = 'CRIADA'
       AND STATUS_NOVO = 'EM_TRANSITO';
    IF V_TOTAL <> 1 THEN
        RAISE_APPLICATION_ERROR(-20101, 'ERRO: Trigger nao registrou auditoria');
    END IF;

    IF PKG_SMART_HAS.FN_PRIORIDADE('ALTO') <> 'PRIORIDADE_ALTA' THEN
        RAISE_APPLICATION_ERROR(-20102, 'ERRO: Function retornou prioridade errada');
    END IF;

    PKG_SMART_HAS.PRC_BUSCAR_ENTREGAS('EM_TRANSITO', V_CURSOR);
    FETCH V_CURSOR INTO V_NUMERO, V_STATUS, V_RISCO;
    IF V_CURSOR%NOTFOUND OR V_NUMERO <> 'ENT001' OR V_STATUS <> 'EM_TRANSITO' THEN
        RAISE_APPLICATION_ERROR(-20103, 'ERRO: Dynamic SQL nao encontrou entrega');
    END IF;
    CLOSE V_CURSOR;

    DBMS_OUTPUT.PUT_LINE('OK: Package, function, procedure, trigger e Dynamic SQL');
END;
/
COMMIT;
SELECT ID, NUMERO, STATUS, RISCO FROM SMH_ENTREGA;
SELECT ID, ENTREGA_ID, STATUS_ANTERIOR, STATUS_NOVO, ALTERADO_EM FROM SMH_AUDITORIA;
