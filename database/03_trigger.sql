-- Smart HAS | Auditoria automatica de mudanca de status
WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE OR REPLACE TRIGGER TRG_SMH_AUDITAR_STATUS
AFTER UPDATE OF STATUS ON SMH_ENTREGA
FOR EACH ROW
WHEN (OLD.STATUS <> NEW.STATUS)
BEGIN
    INSERT INTO SMH_AUDITORIA (ENTREGA_ID, STATUS_ANTERIOR, STATUS_NOVO)
    VALUES (:NEW.ID, :OLD.STATUS, :NEW.STATUS);
END;
/
SHOW ERRORS TRIGGER TRG_SMH_AUDITAR_STATUS
