-- Smart HAS | Package de operacoes e consulta dinamica
WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE OR REPLACE PACKAGE PKG_SMART_HAS AS
    -- Function reutilizavel para classificar prioridade de uma entrega.
    FUNCTION FN_PRIORIDADE(P_RISCO IN VARCHAR2) RETURN VARCHAR2;

    -- Procedure para alterar status de entrega; dispara a trigger de auditoria.
    PROCEDURE PRC_ATUALIZAR_STATUS(P_NUMERO IN VARCHAR2, P_STATUS IN VARCHAR2);

    -- Dynamic SQL com filtro opcional seguro, por bind variable.
    PROCEDURE PRC_BUSCAR_ENTREGAS(P_STATUS IN VARCHAR2, P_CURSOR OUT SYS_REFCURSOR);
END PKG_SMART_HAS;
/

CREATE OR REPLACE PACKAGE BODY PKG_SMART_HAS AS
    FUNCTION FN_PRIORIDADE(P_RISCO IN VARCHAR2) RETURN VARCHAR2 IS
    BEGIN
        IF UPPER(TRIM(P_RISCO)) = 'ALTO' THEN
            RETURN 'PRIORIDADE_ALTA';
        ELSE
            RETURN 'PRIORIDADE_NORMAL';
        END IF;
    END FN_PRIORIDADE;

    PROCEDURE PRC_ATUALIZAR_STATUS(P_NUMERO IN VARCHAR2, P_STATUS IN VARCHAR2) IS
    BEGIN
        IF P_STATUS IS NULL OR TRIM(P_STATUS) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20002, 'Status obrigatorio');
        END IF;

        UPDATE SMH_ENTREGA
           SET STATUS = UPPER(TRIM(P_STATUS)), ATUALIZADO_EM = SYSTIMESTAMP
         WHERE NUMERO = P_NUMERO;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Entrega nao encontrada');
        END IF;
    END PRC_ATUALIZAR_STATUS;

    PROCEDURE PRC_BUSCAR_ENTREGAS(P_STATUS IN VARCHAR2, P_CURSOR OUT SYS_REFCURSOR) IS
        V_SQL VARCHAR2(1000) := 'SELECT NUMERO, STATUS, RISCO FROM SMH_ENTREGA WHERE 1=1';
    BEGIN
        IF P_STATUS IS NOT NULL THEN
            V_SQL := V_SQL || ' AND STATUS = :STATUS';
            OPEN P_CURSOR FOR V_SQL USING UPPER(TRIM(P_STATUS));
        ELSE
            OPEN P_CURSOR FOR V_SQL;
        END IF;
    END PRC_BUSCAR_ENTREGAS;
END PKG_SMART_HAS;
/
SHOW ERRORS PACKAGE PKG_SMART_HAS
SHOW ERRORS PACKAGE BODY PKG_SMART_HAS
