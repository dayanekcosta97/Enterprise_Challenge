-- Smart HAS | Tabelas Oracle para demonstracao de rastreabilidade
WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE TABLE SMH_ENTREGA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO VARCHAR2(50) NOT NULL UNIQUE,
    STATUS VARCHAR2(30) DEFAULT 'CRIADA' NOT NULL,
    RISCO VARCHAR2(30) DEFAULT 'BAIXO' NOT NULL,
    ATUALIZADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE SMH_AUDITORIA (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ENTREGA_ID NUMBER NOT NULL,
    STATUS_ANTERIOR VARCHAR2(30),
    STATUS_NOVO VARCHAR2(30),
    ALTERADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ALTERADO_POR VARCHAR2(128) DEFAULT USER NOT NULL,
    CONSTRAINT FK_SMH_AUDITORIA_ENTREGA FOREIGN KEY (ENTREGA_ID)
        REFERENCES SMH_ENTREGA(ID)
);
